def load_md17(molecule: str, seed: int = 42):
    """Load MD17 with 70/15/15 split. Returns energies in addition to Week 2 outputs."""
    path = MOLECULE_FILES[molecule]
    if not os.path.exists(path):
        raise FileNotFoundError(f"MD17 file not found: {path}")

    data = np.load(path)
    R = torch.tensor(data["R"], dtype=torch.float32)
    F = torch.tensor(data["F"], dtype=torch.float32)
    E = torch.tensor(data["E"], dtype=torch.float32)

    N = len(R)
    rng = np.random.RandomState(seed)
    idx = rng.permutation(N)
    n_train = int(0.70 * N)
    n_cal   = int(0.15 * N)
    train_idx = idx[:n_train]
    cal_idx   = idx[n_train : n_train + n_cal]
    test_idx  = idx[n_train + n_cal :]

    print(f"Molecule: {molecule}")
    print(f"  Total snapshots    : {N}")
    print(f"  Train / Cal / Test : {len(train_idx)} / {len(cal_idx)} / {len(test_idx)}")

    return (
        R[train_idx], R[cal_idx], R[test_idx],
        F[train_idx], F[cal_idx], F[test_idx],
        E[train_idx], E[cal_idx], E[test_idx],
    )


