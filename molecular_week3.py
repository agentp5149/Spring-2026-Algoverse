def save_results(results: dict, out_dir: str = "results/molecular"):
    os.makedirs(out_dir, exist_ok=True)
    fname = f"{results['molecule']}_{results['method']}_{results['split']}.pt"
    path  = os.path.join(out_dir, fname)
