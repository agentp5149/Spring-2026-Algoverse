def run_conformal_with_projection(
    model, cal_R, cal_F, cal_E, test_R, test_F, test_E, alpha, molecule
) -> dict:
    """
    Calibrate conformal predictor, then measure coverage before and after
    projecting test predictions onto the energy conservation manifold.
    """
    print(f"\n--- Conformal + Energy Projection (alpha={alpha}, target={1-alpha:.0%}) ---")

    cal_pred  = get_predictions(model, cal_R)
    test_pred = get_predictions(model, test_R)

    score_fn = TrajectoryNormScore(normalize_by_length=True)
    cp = SplitConformal(score_fn, alpha=alpha)
    cp.calibrate(cal_pred, cal_F)

    eval_before     = cp.evaluate(test_pred, test_F)
    coverage_before = eval_before["coverage"]
    print(f"\n  Coverage BEFORE projection: {coverage_before:.1%}")

    print(f"  Projecting {len(test_pred)} test predictions onto energy manifold...")
    t0 = time.time()
    test_pred_projected = project_forces_energy_constraint(
        test_pred, test_E, n_steps=10, lr=0.01
    )
    print(f"  Projection complete in {time.time() - t0:.1f}s")

    eval_after     = cp.evaluate(test_pred_projected, test_F)
    coverage_after = eval_after["coverage"]
    coverage_loss  = coverage_before - coverage_after
    print(f"  Coverage AFTER projection : {coverage_after:.1%}")
    print(f"  Empirical coverage loss   : {coverage_loss:+.1%}")

    return {
        "surrogate":               "molecular",
        "method":                  "conformal_projected",
        "split":                   "indist",
        "molecule":                molecule,
        "alpha":                   alpha,
        "coverage_before":         coverage_before,
        "coverage_after":          coverage_after,
        "coverage_loss_empirical": coverage_loss,
        "target_coverage":         1 - alpha,
        "mean_width_before":       eval_before["mean_width"],
        "mean_width_after":        eval_after["mean_width"],
        "threshold":               cp.threshold,
        "cal_scores":              cp.cal_scores,
        "n_cal":                   len(cal_R),
        "n_test":                  len(test_R),
        "test_pred_raw":           test_pred,
        "test_pred_projected":     test_pred_projected,
        "ground_truth":            test_F,
        "scores_before":           eval_before["test_scores"],
        "scores_after":            eval_after["test_scores"],
    }


